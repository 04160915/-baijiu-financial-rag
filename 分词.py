# 自检：词典真的生效了吗？
#   抽几个「一旦被切碎就会出大问题」的词，看切出来是不是完好无损。
#   这一步是专门为上面那个 bug 加的 —— 与其指望人记得，
#   不如让程序每次导入时自己喊一声。
