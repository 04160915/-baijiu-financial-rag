PROBE = ["复合计征", "从量计征", "从价计征", "消费税", "税金及附加",
         "应交税费", "营业收入", "从量", "递延所得税资产"]


def verify(verbose=True):
    bad = [w for w in PROBE if cut(w) != [w]]
    if bad and verbose:
        print("[分词] !! 财税词典没生效，这些词被切碎了：%s" % bad)
        print("[分词]    查出来的结果会莫名其妙地差，先查 分词.py 的 WORDS")
    return not bad


